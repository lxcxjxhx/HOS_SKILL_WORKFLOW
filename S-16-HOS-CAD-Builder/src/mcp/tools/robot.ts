const MODULE = "tool:cad_robot_urdf";

// ─── URDF XML Generator ──────────────────────────────────────
function generateURDFXml(config: URDFConfig): string {
  const lines: string[] = [
    `<?xml version="1.0" encoding="UTF-8"?>`,
    `<robot name="${config.robotName}">`,
  ];

  // Materials
  if (config.materials && config.materials.length > 0) {
    lines.push("  <material>");
    for (const mat of config.materials) {
      lines.push(`    <name>${mat.name}</name>`);
      lines.push(`    <color rgba="${mat.color.join(" ")}"/>`);
    }
    lines.push("  </material>");
  }

  // Links
  for (const link of config.links) {
    lines.push(`  <link name="${link.name}">`);
    if (link.visual) {
      lines.push("    <visual>");
      lines.push(`      <geometry><mesh filename="${link.visual.geometry}"/></geometry>`);
      if (link.visual.material) {
        lines.push(`      <material name="${link.visual.material}"/>`);
      }
      lines.push("    </visual>");
    }
    if (link.collision) {
      lines.push("    <collision>");
      lines.push(`      <geometry><mesh filename="${link.collision.geometry}"/></geometry>`);
      lines.push("    </collision>");
    }
    if (link.inertial) {
      lines.push("    <inertial>");
      lines.push(`      <mass value="${link.inertial.mass}"/>`);
      if (link.inertial.origin) {
        lines.push(`      <origin xyz="${link.inertial.origin.join(" ")}"/>`);
      }
      lines.push("    </inertial>");
    }
    lines.push("  </link>");
  }

  // Joints
  for (const joint of config.joints) {
    lines.push(`  <joint name="${joint.name}" type="${joint.type}">`);
    lines.push(`    <parent link="${joint.parent}"/>`);
    lines.push(`    <child link="${joint.child}"/>`);
    if (joint.origin) {
      lines.push(`    <origin xyz="${joint.origin.xyz.join(" ")}" rpy="${joint.origin.rpy.join(" ")}"/>`);
    }
    if (joint.axis) {
      lines.push(`    <axis xyz="${joint.axis.join(" ")}"/>`);
    }
    if (joint.limit) {
      lines.push(
        `    <limit lower="${joint.limit.lower}" upper="${joint.limit.upper}" effort="${joint.limit.effort}" velocity="${joint.limit.velocity}"/>`,
      );
    }
    lines.push("  </joint>");
  }

  lines.push("</robot>");
  return lines.join("\n");
}

// ─── SRDF XML Generator ──────────────────────────────────────
function generateSRDFXml(config: URDFConfig): string {
  const lines: string[] = [
    `<?xml version="1.0" encoding="UTF-8"?>`,
    `<robot name="${config.robotName}">`,
    "  <!-- SRDF generated by HOS-CAD-Builder -->",
  ];

  // Group state
  lines.push('  <group name="all">');
  for (const joint of config.joints) {
    if (joint.type !== "fixed") {
      lines.push(`    <joint name="${joint.name}"/>`);
    }
  }
  lines.push("  </group>");

  // End effectors (last link)
  if (config.links.length > 0) {
    const lastLink = config.links[config.links.length - 1];
    lines.push(`  <end_effector name="end_effector" group="all" parent_link="${lastLink.name}"/>`);
  }

  // Disable collisions between adjacent links
  for (const joint of config.joints) {
    lines.push(`  <disable_collisions link1="${joint.parent}" link2="${joint.child}"/>`);
  }

  lines.push("</robot>");
  return lines.join("\n");
}

