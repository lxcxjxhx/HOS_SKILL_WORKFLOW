export const robotTool = {
  name: "cad_robot_urdf",
  description:
    "Generate URDF and SRDF robot description files from a robot configuration. " +
    "Supports custom configurations and predefined templates (simple-arm, differential-drive).",
  inputSchema: {
    type: "object" as const,
    properties: {
      robot_name: {
        type: "string",
        description: "Name of the robot",
      },
      template: {
        type: "string",
        enum: ["simple-arm", "differential-drive"],
        description: "Use a predefined robot template (ignores other params if set)",
      },
      joints: {
        type: "array",
        description: "Array of joint definitions",
        items: {
          type: "object",
          properties: {
            name: { type: "string" },
            type: { type: "string", enum: ["revolute", "continuous", "prismatic", "fixed", "planar", "floating"] },
            parent: { type: "string" },
            child: { type: "string" },
          },
        },
      },
      links: {
        type: "array",
        description: "Array of link definitions",
        items: {
          type: "object",
          properties: {
            name: { type: "string" },
          },
        },
      },
    },
    required: [],
  },

  async handler(args: { robot_name?: string; template?: string; joints?: any[]; links?: any[] }) {
    logger.info(MODULE, `Generating URDF for "${args.template ?? args.robot_name ?? "custom"}"`);

    try {
      let config: URDFConfig;

      if (args.template && TEMPLATES[args.template]) {
        config = TEMPLATES[args.template]();
      } else {
        config = {
          robotName: args.robot_name ?? "my_robot",
          joints: (args.joints ?? []) as URDFJoint[],
          links: (args.links ?? []) as URDFLink[],
        };
      }

      const urdfXml = generateURDFXml(config);
      const srdfXml = generateSRDFXml(config);

      // Write files
      const outputDir = getConfig().outputDir;
      const urdfPath = join(outputDir, `${config.robotName}.urdf`);
      const srdfPath = join(outputDir, `${config.robotName}.srdf`);
      writeFileSync(urdfPath, urdfXml, "utf-8");
      writeFileSync(srdfPath, srdfXml, "utf-8");

      logger.info(MODULE, `Generated URDF: ${urdfPath}`);
      logger.info(MODULE, `Generated SRDF: ${srdfPath}`);

      const lines: string[] = [
        "## Robot URDF Generated\n",
        `**Robot**: ${config.robotName}`,
        `**Links**: ${config.links.length}`,
        `**Joints**: ${config.joints.length}`,
        `\n**URDF**: ${urdfPath}`,
        `**SRDF**: ${srdfPath}`,
        "\n### URDF Preview\n```xml",
        urdfXml.substring(0, 2000),
        urdfXml.length > 2000 ? "\n... (truncated)" : "",
        "\n```",
      ];

      return {
        content: [{ type: "text" as const, text: lines.join("\n") }],
        isError: false,
      };
    } catch (err) {
      const msg = err instanceof Error ? err.message : String(err);
      logger.error(MODULE, `URDF generation failed: ${msg}`);
      return {
        content: [{ type: "text" as const, text: `**Error**: ${msg}` }],
        isError: true,
      };
    }
  },
};
